#!/usr/bin/env node
// Converts the JSON files produced by export-db.mjs into a single .sql file
// of INSERT statements, ready to run against a fresh Postgres instance
// (e.g. ApsaraDB for PostgreSQL) with `psql`.
//
// Usage:
//   node scripts/generate-import-sql.mjs <export-dir> [output.sql]

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const exportDir = process.argv[2];
const outFile = process.argv[3] || 'import.sql';

if (!exportDir) {
  console.error('Usage: node scripts/generate-import-sql.mjs <export-dir> [output.sql]');
  process.exit(1);
}

function sqlLiteral(value) {
  if (value === null || value === undefined) return 'NULL';
  if (typeof value === 'number') return String(value);
  if (typeof value === 'boolean') return value ? 'TRUE' : 'FALSE';
  if (typeof value === 'object') {
    // jsonb/array columns
    return `'${JSON.stringify(value).replace(/'/g, "''")}'::jsonb`;
  }
  return `'${String(value).replace(/'/g, "''")}'`;
}

const files = readdirSync(exportDir).filter((f) => f.endsWith('.json'));
let sql = `-- Generated by generate-import-sql.mjs — run with:\n-- psql "$DATABASE_URL" -f ${outFile}\n\nBEGIN;\n\n`;

for (const file of files) {
  const table = file.replace(/\.json$/, '');
  const rows = JSON.parse(readFileSync(path.join(exportDir, file), 'utf8'));
  if (rows.length === 0) {
    sql += `-- ${table}: no rows\n\n`;
    continue;
  }
  const columns = Object.keys(rows[0]);
  sql += `-- ${table}: ${rows.length} rows\n`;
  for (const row of rows) {
    const values = columns.map((c) => sqlLiteral(row[c])).join(', ');
    sql += `INSERT INTO public.${table} (${columns.join(', ')}) VALUES (${values}) ON CONFLICT (id) DO NOTHING;\n`;
  }
  sql += '\n';
}

sql += 'COMMIT;\n';
writeFileSync(outFile, sql);
console.log(`Wrote ${outFile} (${files.length} tables)`);
